package ops

import (
	"strings"
	"testing"

	"ledgerline/internal/docs"
)

func TestSurveillanceQuarterlyReport(t *testing.T) {
	o, ctx := setup(t)
	put := func(a Alert) {
		a.Notes = []string{}
		if err := docs.Upsert(ctx, o.Docs, T, cAlert, a.ID, a, "test"); err != nil {
			t.Fatal(err)
		}
	}
	life := func(l AlertLife) {
		if err := docs.Upsert(ctx, o.Docs, T, cAlertLife, l.AlertID, l, "test"); err != nil {
			t.Fatal(err)
		}
	}
	const toi = "Turnover inconsistent with income"
	put(Alert{ID: "A-1", Date: "2026-06-20", Source: "Internal", Type: toi, Status: "Closed"})
	life(AlertLife{AlertID: "A-1", ClosedOn: "2026-07-10"})
	put(Alert{ID: "A-2", Date: "2026-08-01", Source: "NSE", Type: "Synchronised trades", Status: "Under review"})
	put(Alert{ID: "A-3", Date: "2026-09-15", Source: "Internal", Type: toi, Status: "Open"})
	put(Alert{ID: "A-4", Date: "2026-05-01", Source: "Internal", Type: toi, Status: "Closed"})
	life(AlertLife{AlertID: "A-4", ClosedOn: "2026-06-01"})
	put(Alert{ID: "A-5", Date: "2026-10-02", Source: "Internal", Type: toi, Status: "Open"})

	if _, err := o.ReferAlert(ctx, T, "priya.nair", "A-2", "2026-08-20", "Referred"); err == nil {
		t.Fatal("maker referred an alert")
	}
	if _, err := o.ReferAlert(ctx, T, "vikram.shah", "A-2", "2026-08-20", ""); err == nil {
		t.Fatal("referred without observation")
	}
	if _, err := o.ReferAlert(ctx, T, "vikram.shah", "A-2", "2026-08-20", "Client's trades matched a related account; referred with the order log"); err != nil {
		t.Fatal(err)
	}
	if _, err := o.AddSurvAction(ctx, T, "vikram.shah", "2026-Q3", "Reviewed and tightened the turnover-to-income thresholds"); err != nil {
		t.Fatal(err)
	}
	r, err := o.SurvReturnFor(ctx, T, "vikram.shah", "2026-Q3")
	if err != nil {
		t.Fatal(err)
	}
	if r.From != "2026-07-01" || r.To != "2026-09-30" || r.Due != "2026-10-15" || r.Nil {
		t.Fatalf("quarter: %+v", r)
	}
	if len(r.I) != 2 {
		t.Fatalf("format I: %+v", r.I)
	}
	for _, f := range r.I {
		if f.Start+f.New != f.Closed+f.Referred+f.End {
			t.Fatalf("does not add up: %+v", f)
		}
		switch f.Name {
		case toi:
			if f.Start != 1 || f.New != 1 || f.Closed != 1 || f.End != 1 || f.Referred != 0 {
				t.Fatalf("internal: %+v", f)
			}
		case "Synchronised trades (NSE alert)":
			if f.New != 1 || f.Referred != 1 {
				t.Fatalf("exchange alert: %+v", f)
			}
		default:
			t.Fatalf("unexpected %+v", f)
		}
	}
	if len(r.II) != 1 || r.II[0].ReferredOn != "2026-08-20" || len(r.III) != 1 {
		t.Fatalf("formats II/III: %+v %+v", r.II, r.III)
	}
	// The register in Regulatory reports is the same report, for the quarter
	// ended before the date, in the exchanges' formats, and validates.
	rows, err := o.ReportRows(ctx, T, "2026-10-05", "alerts")
	if err != nil {
		t.Fatal(err)
	}
	csv := string(CSV(rows))
	for _, want := range []string{"Format I: Status of Alerts generated by the Trading member", "No. of alerts verified & closed in the quarter", "Format II: Details of alerts referred to the Exchange", "Date referred to Exchange", "20-08-2026", "Format III", "tightened"} {
		if !strings.Contains(csv, want) {
			t.Fatalf("missing %q in\n%s", want, csv)
		}
	}
	if st, err := o.ReportStep(ctx, T, "vikram.shah", "2026-10-05", "alerts", "validate", ""); err != nil || st.Status != "Validated" {
		t.Fatalf("validate: %+v %v", st, err)
	}
	// An empty quarter is a NIL report.
	r, _ = o.survReturn(ctx, T, "2026-Q1")
	if !r.Nil {
		t.Fatal("not nil")
	}
	if rows := survReturnRows(r, "Firm"); !strings.Contains(string(CSV(rows)), "NIL") {
		t.Fatal("no NIL rows")
	}
	if d, _ := reportDef("alerts"); d.Freq != "Quarterly" {
		t.Fatalf("def: %+v", d)
	}
	if d, _ := reportDef("holdings"); d.Freq != "Daily (not Sunday)" || strings.Contains(d.To, "Clients") {
		t.Fatalf("holdings def: %+v", d)
	}
}
