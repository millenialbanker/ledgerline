// ---- surveillance obligation: the quarterly report to the exchanges ----
//
// Trading members report the status of their surveillance alerts to each
// exchange every quarter, within 15 calendar days of the quarter's end, in
// three formats (NSE/SURV/48818 and NSE/SURV/49765, kept in the consolidated
// surveillance circular NSE/SURV/74008 of 30 April 2026; BSE's guidelines on
// quarterly reporting under the surveillance obligation, filed on BEFS):
//
//	Format I   Status of alerts generated by the trading member: Sr. No.,
//	           Name of the Alert, No. of alerts under process at the beginning
//	           of quarter, No. of new alerts generated in the quarter, No. of
//	           alerts verified & closed in the quarter, No. of alerts referred
//	           to Exchange, No. of alerts pending / under process at the end of
//	           quarter.
//	Format II  Details of alerts referred to the Exchange: Sr. No., Date of
//	           Alert, Type of Alert, Brief observation and details of action
//	           taken, Date referred to Exchange.
//	Format III Details of any major surveillance action taken (other than
//	           alerts referred to Exchange): Sr. No., Brief action taken during
//	           the quarter.
//
// A NIL report is filed when Format II or III has nothing; a member that
// traded in the quarter files it even when every count is zero.
//
// An alert is disposed of once: verified and closed (Closed, or STR filed)
// on the day Ledgerline first saw it closed, or referred to the exchange on
// the date the compliance officer records with the observation. Format III
// entries are written by the compliance officer for the quarter.

const (
	cAlertLife  = "alertlife"  // key: alert ID
	cSurvAction = "survaction" // key: quarter|n
)

// AlertLife is when an alert was disposed of.
type AlertLife struct {
	AlertID     string `json:"alert_id"`
	ClosedOn    string `json:"closed_on,omitempty"`
	ReferredOn  string `json:"referred_on,omitempty"`
	Observation string `json:"observation,omitempty"`
	By          string `json:"by,omitempty"`
}

// SurvAction is a Format III entry.
type SurvAction struct {
	ID      string `json:"id"`
	Quarter string `json:"quarter"`
	Text    string `json:"text"`
	By      string `json:"by"`
	At      string `json:"at"`
}

// SurvFormatI is one alert name's counts.
type SurvFormatI struct {
	Name     string `json:"name"`
	Start    int    `json:"start"`
	New      int    `json:"new"`
	Closed   int    `json:"closed"`
	Referred int    `json:"referred"`
	End      int    `json:"end"`
}

// SurvFormatII is one alert referred to the exchange.
type SurvFormatII struct {
	AlertID     string `json:"alert_id"`
	Date        string `json:"date"`
	Type        string `json:"type"`
	Observation string `json:"observation"`
	ReferredOn  string `json:"referred_on"`
}

// SurvReturn is the quarter's report.
type SurvReturn struct {
	Quarter string         `json:"quarter"` // 2026-Q3 (calendar quarter)
	Label   string         `json:"label"`
	From    string         `json:"from"`
	To      string         `json:"to"`
	Due     string         `json:"due"`
	I       []SurvFormatI  `json:"format_i"`
	II      []SurvFormatII `json:"format_ii"`
	III     []SurvAction   `json:"format_iii"`
	Nil     bool           `json:"nil"` // no alert at all in the quarter
}

// survQuarter is the calendar quarter a quarter ID or date names: its first
// and last day.
func survQuarter(q string) (string, string, error) {
	var y, n int
	if _, err := fmt.Sscanf(q, "%d-Q%d", &y, &n); err != nil || n < 1 || n > 4 {
		return "", "", invalid("quarter is written like 2026-Q3 (July to September)")
	}
	from := fmt.Sprintf("%04d-%02d-01", y, (n-1)*3+1)
	to := addDays(addMonths(from, 3), -1)
	return from, to, nil
}

// lastEndedQuarter is the quarter ended before date.
func lastEndedQuarter(date string) string { return quarterID(prevQuarterEnd(date)) }

// trackAlertLife dates closures it has not seen before.
func (o *Ops) trackAlertLife(ctx context.Context, tenant, date string) {
	as, _ := o.Alerts(ctx, tenant)
	for _, a := range as {
		if a.Status != "Closed" && a.Status != "STR filed" {
			continue
		}
		l, _, err := docs.Get[AlertLife](ctx, o.Docs, tenant, cAlertLife, a.ID)
		if err == nil && l.ClosedOn != "" {
			continue
		}
		l.AlertID = a.ID
		l.ClosedOn = date
		if l.ClosedOn < a.Date {
			l.ClosedOn = a.Date
		}
		_ = docs.Upsert(ctx, o.Docs, tenant, cAlertLife, a.ID, l, SystemActor)
	}
}

// ReferAlert records that an alert was referred to the exchange, with the
// observation and action taken (Format II).
func (o *Ops) ReferAlert(ctx context.Context, tenant, actor, id, date, observation string) (AlertLife, error) {
	if err := o.require(ctx, tenant, actor, "Referring an alert to the exchange", RoleCompliance); err != nil {
		return AlertLife{}, err
	}
	a, _, err := docs.Get[Alert](ctx, o.Docs, tenant, cAlert, id)
	if err != nil {
		return AlertLife{}, err
	}
	if !validDate(date) || date < a.Date {
		return AlertLife{}, invalid("give the date the alert was referred to the exchange (on or after the alert date %s)", a.Date)
	}
	if strings.TrimSpace(observation) == "" {
		return AlertLife{}, invalid("write the brief observation and the action taken")
	}
	l, _, _ := docs.GetOr(ctx, o.Docs, tenant, cAlertLife, id, AlertLife{AlertID: id})
	l.ReferredOn, l.Observation, l.By = date, strings.TrimSpace(observation), actor
	if err := docs.Upsert(ctx, o.Docs, tenant, cAlertLife, id, l, actor); err != nil {
		return l, err
	}
	o.log(ctx, tenant, actor, "alert.referred", id, map[string]any{"date": date})
	return l, nil
}

// AddSurvAction adds a Format III entry for a quarter.
func (o *Ops) AddSurvAction(ctx context.Context, tenant, actor, quarter, text string) (SurvAction, error) {
	if err := o.require(ctx, tenant, actor, "Recording a surveillance action", RoleCompliance); err != nil {
		return SurvAction{}, err
	}
	if _, _, err := survQuarter(quarter); err != nil {
		return SurvAction{}, err
	}
	if strings.TrimSpace(text) == "" {
		return SurvAction{}, invalid("describe the action taken")
	}
	have, _ := docs.List[SurvAction](ctx, o.Docs, tenant, cSurvAction, quarter+"|")
	x := SurvAction{ID: fmt.Sprintf("%s|%03d", quarter, len(have)+1), Quarter: quarter, Text: strings.TrimSpace(text), By: actor, At: o.now().Format(time.RFC3339)}
	if err := docs.Upsert(ctx, o.Docs, tenant, cSurvAction, x.ID, x, actor); err != nil {
		return x, err
	}
	o.log(ctx, tenant, actor, "surveillance.action", x.ID, nil)
	return x, nil
}

// SurvReturnFor builds a quarter's report ("" = the quarter ended before
// the business date).
func (o *Ops) SurvReturnFor(ctx context.Context, tenant, actor, quarter string) (SurvReturn, error) {
	if err := o.require(ctx, tenant, actor, "Viewing the surveillance report", RoleCompliance, RoleChecker); err != nil {
		return SurvReturn{}, err
	}
	return o.survReturn(ctx, tenant, firstOf(quarter, lastEndedQuarter(o.businessDate(ctx, tenant))))
}

func (o *Ops) survReturn(ctx context.Context, tenant, quarter string) (SurvReturn, error) {
	from, to, err := survQuarter(quarter)
	if err != nil {
		return SurvReturn{}, err
	}
	o.trackAlertLife(ctx, tenant, o.businessDate(ctx, tenant))
	r := SurvReturn{Quarter: quarter, Label: quarterLabel(to), From: from, To: to, Due: addDays(to, 15), I: []SurvFormatI{}, II: []SurvFormatII{}, III: []SurvAction{}}
	as, err := o.Alerts(ctx, tenant)
	if err != nil {
		return r, err
	}
	lives, _ := docs.List[AlertLife](ctx, o.Docs, tenant, cAlertLife, "")
	life := map[string]AlertLife{}
	for _, l := range lives {
		life[l.AlertID] = l
	}
	by := map[string]*SurvFormatI{}
	sort.SliceStable(as, func(i, j int) bool { return as[i].Date < as[j].Date || as[i].Date == as[j].Date && as[i].ID < as[j].ID })
	for _, a := range as {
		if a.Date == "" || a.Date > to {
			continue
		}
		l := life[a.ID]
		// Disposed of once: referred to the exchange, or verified and closed.
		disp, referred := l.ClosedOn, false
		if l.ReferredOn != "" && (disp == "" || l.ReferredOn <= disp) {
			disp, referred = l.ReferredOn, true
		}
		if disp != "" && disp < from {
			continue // disposed of in an earlier quarter
		}
		name := a.Type
		if a.Source != "" && a.Source != "Internal" {
			name += " (" + a.Source + " alert)"
		}
		f := by[name]
		if f == nil {
			f = &SurvFormatI{Name: name}
			by[name] = f
		}
		if a.Date < from {
			f.Start++
		} else {
			f.New++
		}
		switch {
		case disp == "" || disp > to:
			f.End++
		case referred:
			f.Referred++
			r.II = append(r.II, SurvFormatII{AlertID: a.ID, Date: a.Date, Type: a.Type, Observation: l.Observation, ReferredOn: l.ReferredOn})
		default:
			f.Closed++
		}
	}
	for _, k := range sortedKeys(by) {
		r.I = append(r.I, *by[k])
	}
	if acts, _ := docs.List[SurvAction](ctx, o.Docs, tenant, cSurvAction, quarter+"|"); acts != nil {
		r.III = acts
	}
	r.Nil = len(r.I) == 0
	return r, nil
}

// survReturnRows is the report as one CSV: the three formats one under the
// other, each with its heading, all rows as wide as Format I.
func survReturnRows(r SurvReturn, firm string) [][]string {
	const w = 7
	pad := func(xs ...string) []string {
		for len(xs) < w {
			xs = append(xs, "")
		}
		return xs
	}
	rows := [][]string{pad("Quarterly reporting under surveillance obligation", firm, "Quarter "+r.Label, "Due "+r.Due)}
	rows = append(rows, pad(), pad("Format I: Status of Alerts generated by the Trading member"),
		pad("Sr. No.", "Name of the Alert", "No. of alerts under process at the beginning of quarter", "No. of new alerts generated in the quarter", "No. of alerts verified & closed in the quarter", "No. of alerts referred to Exchange (*)", "No. of alerts pending / under process at the end of quarter"))
	if len(r.I) == 0 {
		rows = append(rows, pad("1", "NIL", "0", "0", "0", "0", "0"))
	}
	for i, f := range r.I {
		rows = append(rows, pad(fmt.Sprint(i+1), f.Name, fmt.Sprint(f.Start), fmt.Sprint(f.New), fmt.Sprint(f.Closed), fmt.Sprint(f.Referred), fmt.Sprint(f.End)))
	}
	rows = append(rows, pad(), pad("Format II: Details of alerts referred to the Exchange"), pad("Sr. No.", "Date of Alert", "Type of Alert", "Brief observation and details of action taken", "Date referred to Exchange"))
	if len(r.II) == 0 {
		rows = append(rows, pad("NIL"))
	}
	for i, x := range r.II {
		rows = append(rows, pad(fmt.Sprint(i+1), fmtDashDMY(x.Date), x.Type, x.Observation, fmtDashDMY(x.ReferredOn)))
	}
	rows = append(rows, pad(), pad("Format III: Details of any major surveillance action taken (other than alerts referred to Exchange)"), pad("Sr. No.", "Brief action taken during the quarter"))
	if len(r.III) == 0 {
		rows = append(rows, pad("NIL"))
	}
	for i, x := range r.III {
		rows = append(rows, pad(fmt.Sprint(i+1), x.Text))
	}
	return rows
}

func fmtDashDMY(d string) string {
	t, err := time.Parse("2006-01-02", d)
	if err != nil {
		return d
	}
	return t.Format("02-01-2006")
}
