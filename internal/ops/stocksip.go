// ---- stock SIPs: the register ----
//
// A stock SIP is a client's standing instruction to buy a share or an ETF
// for a fixed amount (or a fixed number of shares) every day, week or
// month. No exchange or depository runs equity SIPs: it is the broker's
// own feature, so Ledgerline keeps the register, works out each instalment
// (price, quantity, funds), and hands the orders to the trading front end
// (OMS). Ledgerline does not place orders itself; the trades come back in
// the exchange trade files like any other and are billed, noted and
// lotted the usual way.
//
// What the firm decides (Settings on the Stock SIPs screen, by the
// compliance officer): order type (market with protection, or limit),
// placement time, whether SIP orders are tagged as algo orders (SEBI's
// retail algo framework applies to all brokers from 1 April 2026 and an
// "algo" is any order generated by automated execution logic; whether a
// scheduled SIP order is one is the firm's call), the scrips allowed, the
// failures after which a SIP stops, the minimum ticket, brokerage, and
// whether shortfalls are topped up by UPI AutoPay or e-mandate.
//
// Each SIP carries the client's consent: the standing instruction's
// wording and version, when and how it was given; cancelling revokes it.

const (
	cStockSIP   = "stocksip"
	cSIPOrder   = "stocksiporder"
	cSIPConf    = "stocksipconf"
	cSIPList    = "stocksiplist"
	cSIPBatch   = "stocksipbatch"
	cSIPMandate = "stocksipmandate"
	cSIPTopup   = "stocksiptopup"
	cSIPRun     = "stocksiprun"
)

// SIP bases, frequencies and statuses.
const (
	SIPAmount = "amount"
	SIPQty    = "qty"

	SIPDaily   = "daily"
	SIPWeekly  = "weekly"
	SIPMonthly = "monthly"

	SIPActive    = "Active"
	SIPPaused    = "Paused"
	SIPCancelled = "Cancelled"
	SIPCompleted = "Completed"
)

// SIPSettings are the firm's rules for stock SIPs.
type SIPSettings struct {
	Enabled bool `json:"enabled"`
	// OrderType is MARKET (with ProtectionPct as the market protection the
	// OMS applies) or LIMIT (at the price plus ProtectionPct, rounded down
	// to TickSize).
	OrderType     string `json:"order_type"`
	ProtectionPct string `json:"protection_pct"`
	TickSize      string `json:"tick_size"`
	PlaceAt       string `json:"place_at"` // HH:MM IST
	// Router hands orders to the OMS: basket (a file the dealer uploads),
	// xts (Symphony XTS order entry) or other (a vendor API not yet built).
	Router       string `json:"router"`
	BasketFormat string `json:"basket_format"` // layout in config/formats
	// Eligibility is list (only the firm's list of scrips) or any (any
	// equity share or ETF). ASM/GSM and other restricted scrips (the
	// restricted list), trade-for-trade series and suspended scrips are
	// never allowed.
	Eligibility string       `json:"eligibility"`
	MaxFailures int          `json:"max_failures"` // consecutive failed instalments before a SIP stops
	MinAmount   money.Amount `json:"min_amount"`   // minimum order value
	// BrokerageChannel is the brokerage plan channel SIP orders are priced
	// under (map the SIP dealer terminal to it in Brokerage setup);
	// BrokeragePerInstalment is used when no plan line applies.
	BrokerageChannel       string       `json:"brokerage_channel,omitempty"`
	BrokeragePerInstalment money.Amount `json:"brokerage_per_instalment"`
	AlgoTag                bool         `json:"algo_tag"`
	AlgoID                 string       `json:"algo_id,omitempty"`
	// Top-ups: a UPI AutoPay or e-mandate debit on the day before the
	// instalment for the shortfall, at most TopupCap (₹15,000: RBI's limit
	// for e-mandate debits without additional authentication), raised at
	// TopupAt the day before the debit so the client has 24 hours' notice.
	Topups   bool         `json:"topups"`
	TopupCap money.Amount `json:"topup_cap"`
	TopupAt  string       `json:"topup_at"`
	// The standing instruction's wording; a change makes a new version.
	ConsentText    string `json:"consent_text"`
	ConsentVersion int    `json:"consent_version"`
	DecidedBy      string `json:"decided_by,omitempty"` // who set the order type, time and algo tag
	DecidedAt      string `json:"decided_at,omitempty"`
	UpdatedBy      string `json:"updated_by,omitempty"`
	UpdatedAt      string `json:"updated_at,omitempty"`
}

// sipTopupLimit is RBI's limit for e-mandate debits without an additional
// factor of authentication (RBI notification 12570:
// https://www.rbi.org.in/Scripts/NotificationUser.aspx?Id=12570).
const sipTopupLimit money.Amount = 1500000

const defaultSIPConsent = "I authorise {firm} to buy {scrip} in my trading account {ucc} {basis} {frequency}, from {start}{end}, as a delivery (CNC) order placed through the firm's trading system at about {place_at} on each instalment day ({order_type}). I understand that: the quantity is the amount divided by the last traded price, rounded down to whole shares, and no order is placed if that is less than one share; an instalment falling on a holiday is placed on the next trading day; no order (and no partial order) is placed if my free funds are not enough for the order and its charges; an order not executed by the end of the day lapses; brokerage ({brokerage}) and statutory charges apply to each order; the SIP stops after {max_failures} instalments in a row are not executed; and I can pause or cancel it at any time before the placement time. This is my own decision; the firm does not advise me on it."

// DefaultSIPSettings are used until the firm saves its own.
func DefaultSIPSettings() SIPSettings {
	return SIPSettings{OrderType: "LIMIT", ProtectionPct: "2", TickSize: "0.05", PlaceAt: "11:00", Router: "basket", BasketFormat: "stocksip-basket",
		Eligibility: "list", MaxFailures: 5, MinAmount: 10000, TopupCap: sipTopupLimit, TopupAt: "10:00", ConsentText: defaultSIPConsent, ConsentVersion: 1}
}

func (o *Ops) sipSettings(ctx context.Context, tenant string) SIPSettings {
	c, _, _ := docs.GetOr(ctx, o.Docs, tenant, cSIPConf, "main", DefaultSIPSettings())
	d := DefaultSIPSettings()
	if c.OrderType == "" {
		c.OrderType = d.OrderType
	}
	if c.TickSize == "" {
		c.TickSize = d.TickSize
	}
	if c.PlaceAt == "" {
		c.PlaceAt = d.PlaceAt
	}
	if c.Router == "" {
		c.Router = d.Router
	}
	if c.BasketFormat == "" {
		c.BasketFormat = d.BasketFormat
	}
	if c.Eligibility == "" {
		c.Eligibility = d.Eligibility
	}
	if c.MaxFailures <= 0 {
		c.MaxFailures = d.MaxFailures
	}
	if c.TopupCap <= 0 || c.TopupCap > sipTopupLimit {
		c.TopupCap = sipTopupLimit
	}
	if c.TopupAt == "" {
		c.TopupAt = d.TopupAt
	}
	if c.ConsentText == "" {
		c.ConsentText = d.ConsentText
	}
	c.ConsentVersion = max(c.ConsentVersion, 1)
	return c
}

