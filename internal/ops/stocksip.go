// SIPEvent is one change to a SIP.
type SIPEvent struct {
	At   string `json:"at"`
	By   string `json:"by"`
	What string `json:"what"`
}

// StockSIP is one client's SIP in one scrip.
type StockSIP struct {
	ID          string       `json:"id"`
	UCC         string       `json:"ucc"`
	Name        string       `json:"name"`
	Exchange    string       `json:"exchange"`
	Symbol      string       `json:"symbol"`
	ISIN        string       `json:"isin"`
	Company     string       `json:"company,omitempty"`
	Basis       string       `json:"basis"` // amount or qty
	Amount      money.Amount `json:"amount,omitempty"`
	Qty         int64        `json:"qty,omitempty"`
	Frequency   string       `json:"frequency"`     // daily, weekly, monthly
	Day         int          `json:"day,omitempty"` // weekly 1 (Mon) to 5 (Fri); monthly 1 to 31 (last day of shorter months)
	Start       string       `json:"start"`
	End         string       `json:"end,omitempty"`
	Status      string       `json:"status"`
	PausedUntil string       `json:"paused_until,omitempty"`
	Pauses      []SIPPause   `json:"pauses,omitempty"`
	Skips       []string     `json:"skips,omitempty"`     // scheduled dates to skip
	Failures    int          `json:"failures"`            // consecutive
	Done        int          `json:"done"`                // instalments bought (fully or partly)
	Failed      int          `json:"failed"`              // instalments not bought, in all
	LastDate    string       `json:"last_date,omitempty"` // last instalment's trade date
	Consent     SIPConsent   `json:"consent"`
	CreatedAt   string       `json:"created_at"`
	CreatedBy   string       `json:"created_by"`
	StopReason  string       `json:"stop_reason,omitempty"`
	History     []SIPEvent   `json:"history,omitempty"`
}

func (s *StockSIP) event(at, by, what string) {
	s.History = append(s.History, SIPEvent{At: at, By: by, What: what})
	if len(s.History) > 50 {
		s.History = s.History[len(s.History)-50:]
	}
}

// Describe is "₹5,000 monthly on day 5" or "10 shares weekly on Wednesday".
func (s StockSIP) Describe() string {
	return s.basisText() + " " + s.frequencyText()
}

func (s StockSIP) basisText() string {
	if s.Basis == SIPQty {
		return fmt.Sprintf("%d shares", s.Qty)
	}
	return "for ₹" + formatINR(s.Amount.Dec())
}

var weekdayNames = []string{"Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"}

func (s StockSIP) frequencyText() string {
	switch s.Frequency {
	case SIPWeekly:
		return "every " + weekdayNames[s.Day%7]
	case SIPMonthly:
		return fmt.Sprintf("monthly on day %d", s.Day)
	}
	return "every trading day"
}

// SIPRequest is what a new SIP is made from.
type SIPRequest struct {
	UCC       string       `json:"ucc"`
	Exchange  string       `json:"exchange"`
	Symbol    string       `json:"symbol"`
	ISIN      string       `json:"isin"`
	Basis     string       `json:"basis"`
	Amount    money.Amount `json:"amount"`
	Qty       int64        `json:"qty"`
	Frequency string       `json:"frequency"`
	Day       int          `json:"day"`
	Start     string       `json:"start"`
	End       string       `json:"end"`
	// Consent: a client in the portal agrees to the wording shown; staff
	// record how the client gave it (signed form or recorded call) and its
	// reference.
	Consent        bool   `json:"consent"`
	ConsentVersion int    `json:"consent_version"`
	ConsentSource  string `json:"consent_source"`
	ConsentRef     string `json:"consent_ref"`
}

// sipConsentText fills the firm's wording for one SIP.
func sipConsentText(cfg SIPSettings, set Settings, s StockSIP) string {
	end := ""
	if s.End != "" {
		end = " to " + fmtDay(s.End)
	} else {
		end = " until I cancel it"
	}
	ot := "a limit order at up to " + cfg.ProtectionPct + "% above the last traded price"
	if cfg.OrderType == "MARKET" {
		ot = "a market order with " + cfg.ProtectionPct + "% market protection"
	}
	if cfg.AlgoTag {
		ot += ", tagged as an algo order"
	}
	brok := "as per my brokerage plan"
	if cfg.BrokerageChannel == "" && cfg.BrokeragePerInstalment > 0 {
		brok = "₹" + formatINR(cfg.BrokeragePerInstalment.Dec()) + " plus GST"
	}
	basis := s.basisText()
	if s.Basis == SIPAmount {
		basis = "for ₹" + formatINR(s.Amount.Dec()) + " each time"
	} else {
		basis = fmt.Sprintf("%d shares each time", s.Qty)
	}
	r := strings.NewReplacer("{firm}", firstOf(set.Firm, "the firm"), "{scrip}", s.Symbol+" ("+s.ISIN+", "+s.Exchange+")", "{ucc}", s.UCC, "{basis}", basis,
		"{frequency}", s.frequencyText(), "{start}", fmtDay(s.Start), "{end}", end, "{place_at}", cfg.PlaceAt, "{order_type}", ot,
		"{brokerage}", brok, "{max_failures}", strconv.Itoa(cfg.MaxFailures))
	return r.Replace(cfg.ConsentText)
}

// StockSIPs lists SIPs, for one client or all.
func (o *Ops) StockSIPs(ctx context.Context, tenant, ucc string) ([]StockSIP, error) {
	all, err := docs.List[StockSIP](ctx, o.Docs, tenant, cStockSIP, "")
	if err != nil {
		return nil, err
	}
	out := []StockSIP{}
	for _, s := range all {
		if ucc == "" || s.UCC == strings.ToUpper(ucc) {
			out = append(out, s)
		}
	}
	return out, nil
}

// sipClientActor says whether actor is a portal login, and checks a
// portal login may act for ucc.
func (o *Ops) sipClientActor(ctx context.Context, tenant, actor, ucc string) (bool, error) {
	role, err := o.RoleOf(ctx, tenant, actor)
	if err != nil || role != RoleClient {
		return false, nil
	}
	accts, err := o.PortalAccounts(ctx, tenant, actor)
	if err != nil {
		return true, err
	}
	if !contains(accts, strings.ToUpper(ucc)) {
		return true, ErrNotFound
	}
	return true, nil
}

// SIPPreview is a SIP as it would be registered, with the standing
// instruction the client agrees to.
type SIPPreview struct {
	SIP            StockSIP     `json:"sip"`
	ConsentText    string       `json:"consent_text"`
	ConsentVersion int          `json:"consent_version"`
	Price          money.Dec    `json:"price"`
	QtyNow         int64        `json:"qty_now"`
	Next           string       `json:"next"`       // first instalment date
	NextTrade      string       `json:"next_trade"` // the trading day it is placed on
	Estimate       money.Amount `json:"estimate"`   // funds the first instalment needs at today's price
}

// PreviewStockSIP checks a SIP request and shows the standing instruction
// for it, without registering it.
func (o *Ops) PreviewStockSIP(ctx context.Context, tenant, actor, date string, r SIPRequest) (SIPPreview, error) {
	if client, err := o.sipClientActor(ctx, tenant, actor, r.UCC); err != nil {
		return SIPPreview{}, err
	} else if !client {
		if err := o.require(ctx, tenant, actor, "Registering a stock SIP for a client", RoleMaker, RoleChecker); err != nil {
			return SIPPreview{}, err
		}
	}
	s, cfg, set, inst, err := o.sipBuild(ctx, tenant, date, r)
	if err != nil {
		return SIPPreview{}, err
	}
	p := SIPPreview{SIP: s, ConsentText: sipConsentText(cfg, set, s), ConsentVersion: cfg.ConsentVersion, Price: sipPrice(inst)}
	p.Next = sipNextScheduled(s, set, s.Start)
	p.NextTrade = sipTradeDate(set, p.Next)
	p.QtyNow = s.Qty
	if s.Basis == SIPAmount {
		p.QtyNow = floorDiv(s.Amount.Dec(), p.Price)
	}
	if p.QtyNow > 0 {
		worst := p.Price.Add(p.Price.Pct(dec(cfg.ProtectionPct)))
		p.Estimate = worst.MulInt(p.QtyNow).Add(o.sipCharges(ctx, tenant, cfg, s.UCC, s.Exchange, firstOf(p.NextTrade, s.Start), p.QtyNow, worst)).CeilRupee().Round(money.UnitPaisa)
	}
	return p, nil
}

// CreateStockSIP registers a SIP. Staff need the client's consent
// reference; a client in the portal agrees to the wording shown (the
// version they saw must be the current one).
func (o *Ops) CreateStockSIP(ctx context.Context, tenant, actor, date string, r SIPRequest) (StockSIP, error) {
	r.UCC = strings.ToUpper(strings.TrimSpace(r.UCC))
	src, ref := SrcPortal, ""
	if client, err := o.sipClientActor(ctx, tenant, actor, r.UCC); err != nil {
		return StockSIP{}, err
	} else if client {
		if !r.Consent {
			return StockSIP{}, invalid("read the standing instruction and tick that you agree to it")
		}
	} else {
		if err := o.require(ctx, tenant, actor, "Registering a stock SIP for a client", RoleMaker, RoleChecker); err != nil {
			return StockSIP{}, err
		}
		if r.ConsentSource != SrcForm && r.ConsentSource != SrcCall {
			return StockSIP{}, invalid("record how the client gave the standing instruction: %s or %s", SrcForm, SrcCall)
		}
		if strings.TrimSpace(r.ConsentRef) == "" {
			return StockSIP{}, invalid("give the form number or call recording reference of the client's instruction")
		}
		src, ref = r.ConsentSource, strings.TrimSpace(r.ConsentRef)
	}
	s, cfg, set, _, err := o.sipBuild(ctx, tenant, date, r)
	if err != nil {
		return s, err
	}
	if r.ConsentVersion != 0 && r.ConsentVersion != cfg.ConsentVersion {
		return StockSIP{}, fmt.Errorf("%w: the standing instruction's wording has changed; read it again", ErrState)
	}
	n, err := o.next(ctx, tenant, "stocksip", actor)
	if err != nil {
		return s, err
	}
	now := o.now().Format(time.RFC3339)
	s.ID = fmt.Sprintf("SIP-%06d", n)
	s.CreatedAt, s.CreatedBy = now, actor
	s.Consent = SIPConsent{Version: cfg.ConsentVersion, Text: sipConsentText(cfg, set, s), At: now, By: actor, Source: src, Ref: ref}
	s.event(now, actor, "Registered: "+s.Describe()+" ("+src+")")
	if _, err := docs.Put(ctx, o.Docs, tenant, cStockSIP, s.ID, s, 0, actor); err != nil {
		return s, err
	}
	o.log(ctx, tenant, actor, "stocksip.created", s.ID, map[string]any{"ucc": s.UCC, "symbol": s.Symbol, "basis": s.Basis, "amount": s.Amount.String(), "qty": s.Qty,
		"frequency": s.Frequency, "day": s.Day, "consent_version": s.Consent.Version, "consent_source": src})
	return s, nil
}

// sipBuild checks a SIP request and makes the SIP (not yet stored).
func (o *Ops) sipBuild(ctx context.Context, tenant, date string, r SIPRequest) (StockSIP, SIPSettings, Settings, Instrument, error) {
	r.UCC = strings.ToUpper(strings.TrimSpace(r.UCC))
	cfg := o.sipSettings(ctx, tenant)
	set, _ := o.Settings(ctx, tenant)
	fail := func(err error) (StockSIP, SIPSettings, Settings, Instrument, error) {
		return StockSIP{}, cfg, set, Instrument{}, err
	}
	if !cfg.Enabled {
		return fail(fmt.Errorf("%w: the firm has not switched stock SIPs on", ErrState))
	}
	c, err := o.Client(ctx, tenant, r.UCC)
	if err != nil {
		return fail(invalid("client %s not found", r.UCC))
	}
	if why := sipClientBar(c); why != "" {
		return fail(invalid("%s", why))
	}
	if !validDate(date) {
		date = o.businessDate(ctx, tenant)
	}
	today := o.now().Format("2006-01-02")
	s := StockSIP{UCC: c.UCC, Name: c.Name, Exchange: strings.ToUpper(firstOf(strings.TrimSpace(r.Exchange), "NSE")), Basis: r.Basis, Amount: r.Amount, Qty: r.Qty,
		Frequency: strings.ToLower(r.Frequency), Day: r.Day, Start: firstOf(r.Start, today), End: r.End, Status: SIPActive}
	switch {
	case s.Exchange != "NSE" && s.Exchange != "BSE":
		return fail(invalid("SIP orders go to NSE or BSE"))
	case !validDate(s.Start) || (s.End != "" && !validDate(s.End)):
		return fail(invalid("dates are YYYY-MM-DD"))
	case s.Start < today:
		return fail(invalid("a SIP cannot start in the past"))
	case s.End != "" && s.End < s.Start:
		return fail(invalid("the end date is before the start"))
	}
	switch s.Frequency {
	case SIPDaily:
		s.Day = 0
	case SIPWeekly:
		if s.Day < 1 || s.Day > 5 {
			return fail(invalid("a weekly SIP runs on a weekday: 1 (Monday) to 5 (Friday)"))
		}
	case SIPMonthly:
		if s.Day < 1 || s.Day > 31 {
			return fail(invalid("a monthly SIP runs on a day from 1 to 31 (the last day in shorter months)"))
		}
	default:
		return fail(invalid("frequency is daily, weekly or monthly"))
	}
	look, _, _ := o.liveLookup(ctx, tenant, date, "")
	inst, why := o.sipScrip(ctx, tenant, cfg, look, s.Exchange, r.Symbol, r.ISIN)
	if why != "" {
		return fail(invalid("%s", why))
	}
	s.Symbol, s.ISIN, s.Company = inst.Symbol, inst.ISIN, inst.Company
	px := sipPrice(inst)
	switch s.Basis {
	case SIPAmount:
		s.Qty = 0
		if s.Amount <= 0 {
			return fail(invalid("give the amount for each instalment"))
		}
		if s.Amount < cfg.MinAmount {
			return fail(invalid("the minimum SIP instalment is ₹%s", formatINR(cfg.MinAmount.Dec())))
		}
		if px.Sign() > 0 && s.Amount.Dec().Cmp(px) < 0 {
			return fail(invalid("₹%s does not buy one share of %s at ₹%s", formatINR(s.Amount.Dec()), s.Symbol, px.Fixed(2)))
		}
	case SIPQty:
		s.Amount = 0
		if s.Qty < 1 || s.Qty > 1_000_000 {
			return fail(invalid("give the number of shares for each instalment"))
		}
		if px.Sign() > 0 && px.MulInt(s.Qty).Cmp(cfg.MinAmount.Dec()) < 0 {
			return fail(invalid("%d shares at ₹%s is below the minimum SIP order of ₹%s", s.Qty, px.Fixed(2), formatINR(cfg.MinAmount.Dec())))
		}
	default:
		return fail(invalid("a SIP is for an amount or a number of shares"))
	}
	return s, cfg, set, inst, nil
}

// sipClientBar says why a client cannot buy through a SIP now ("" if they can).
func sipClientBar(c Client) string {
	switch {
	case c.Status != "Active":
		return "the account is not active"
	case c.Inactive:
		return "the account is flagged inactive; it must be reactivated first"
	case c.Blocked:
		return "the account is blocked from buying" + func() string {
			if c.BlockedReason != "" {
				return " (" + c.BlockedReason + ")"
			}
			return ""
		}()
	case !c.SegmentOpen("CM"):
		return "the cash segment is not open for this account"
	}
	return ""
}

// ChangeStockSIP pauses, resumes, skips an instalment of, or cancels a SIP.
// until is the last day of a pause ("" until resumed); date is the
// scheduled date to skip ("" for the next one).
func (o *Ops) ChangeStockSIP(ctx context.Context, tenant, actor, id, action, until, date, reason string) (StockSIP, error) {
	cur, _, err := docs.Get[StockSIP](ctx, o.Docs, tenant, cStockSIP, id)
	if err != nil {
		return cur, err
	}
	if role, err := o.RoleOf(ctx, tenant, actor); err == nil && role == RoleClient {
		accts, err := o.PortalAccounts(ctx, tenant, actor)
		if err != nil {
			return cur, err
		}
		if !contains(accts, cur.UCC) {
			return cur, ErrNotFound
		}
	} else if err := o.require(ctx, tenant, actor, "Changing a stock SIP", RoleMaker, RoleChecker); err != nil {
		return cur, err
	}
	set, _ := o.Settings(ctx, tenant)
	today := o.now().Format("2006-01-02")
	now := o.now().Format(time.RFC3339)
	what := ""
	s, err := docs.Update(ctx, o.Docs, tenant, cStockSIP, id, actor, func(s *StockSIP) error {
		if s.Status == SIPCancelled || s.Status == SIPCompleted {
			return fmt.Errorf("%w: SIP %s is %s", ErrState, s.ID, strings.ToLower(s.Status))
		}
		switch action {
		case "pause":
			if until != "" && (!validDate(until) || until < today) {
				return invalid("pause until a date from today (YYYY-MM-DD), or leave it empty to pause until resumed")
			}
			s.Status, s.PausedUntil = SIPPaused, until
			s.Pauses = append(s.Pauses, SIPPause{From: today, Until: until, By: actor, At: now})
			what = "Paused" + map[bool]string{true: " until " + until, false: ""}[until != ""]
		case "resume":
			if s.Status != SIPPaused {
				return fmt.Errorf("%w: SIP %s is not paused", ErrState, s.ID)
			}
			s.Status, s.PausedUntil = SIPActive, ""
			if n := len(s.Pauses); n > 0 && s.Pauses[n-1].Until == "" {
				s.Pauses[n-1].Until = today
			}
			what = "Resumed"
		case "skip":
			d := date
			if d == "" {
				d = sipNextScheduled(*s, set, today)
			}
			if !validDate(d) || d < today {
				return invalid("give the instalment date to skip")
			}
			if !s.scheduledOn(d, set) {
				return invalid("%s is not an instalment date of this SIP", d)
			}
			if !contains(s.Skips, d) {
				s.Skips = append(s.Skips, d)
				sort.Strings(s.Skips)
			}
			what = "Instalment of " + d + " skipped"
		case "cancel":
			s.Status, s.StopReason = SIPCancelled, firstOf(strings.TrimSpace(reason), "cancelled by "+actor)
			s.Consent.RevokedAt, s.Consent.RevokedBy = now, actor
			what = "Cancelled; standing instruction revoked: " + s.StopReason
		default:
			return invalid("action is pause, resume, skip or cancel")
		}
		s.event(now, actor, what)
		return nil
	})
	if err != nil {
		return s, err
	}
	o.log(ctx, tenant, actor, "stocksip."+action, id, map[string]any{"ucc": s.UCC, "what": what})
	return s, nil
}

// scheduledOn says whether the SIP has an instalment scheduled on date x
// (before moving holidays): daily SIPs on trading days, weekly on their
// weekday, monthly on their day (the month's last day when shorter).
func (s StockSIP) scheduledOn(x string, set Settings) bool {
	t, err := time.Parse("2006-01-02", x)
	if err != nil || x < s.Start || (s.End != "" && x > s.End) {
		return false
	}
	switch s.Frequency {
	case SIPDaily:
		return set.IsBusinessDay(x)
	case SIPWeekly:
		return int(t.Weekday()) == s.Day
	case SIPMonthly:
		last := time.Date(t.Year(), t.Month()+1, 0, 0, 0, 0, 0, time.UTC).Day()
		return t.Day() == min(s.Day, last)
	}
	return false
}

// scheduledFor lists the scheduled dates that fall to trade date d: those
// after the previous trading day, up to d (a holiday's instalment moves to
// the next trading day).
func (s StockSIP) scheduledFor(set Settings, d string) []string {
	if !set.IsBusinessDay(d) {
		return nil
	}
	prev := set.PrevBusinessDay(d)
	t, err := time.Parse("2006-01-02", prev)
	if err != nil {
		return nil
	}
	var out []string
	for i := 0; i < 40; i++ {
		t = t.AddDate(0, 0, 1)
		x := t.Format("2006-01-02")
		if x > d {
			break
		}
		if s.scheduledOn(x, set) {
			out = append(out, x)
		}
	}
	return out
}

// sipNextScheduled is the next scheduled date on or after from.
func sipNextScheduled(s StockSIP, set Settings, from string) string {
	t, err := time.Parse("2006-01-02", max(from, s.Start))
	if err != nil {
		return ""
	}
	for i := 0; i < 400; i++ {
		x := t.Format("2006-01-02")
		if s.End != "" && x > s.End {
			return ""
		}
		if s.scheduledOn(x, set) && !contains(s.Skips, x) {
			return x
		}
		t = t.AddDate(0, 0, 1)
	}
	return ""
}

// sipTradeDate is the trading day a scheduled date is placed on.
func sipTradeDate(set Settings, x string) string {
	if x == "" || set.IsBusinessDay(x) {
		return x
	}
	return set.NextBusinessDay(x)
}

