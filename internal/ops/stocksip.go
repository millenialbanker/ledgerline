// SIPListItem is one scrip on the eligible or restricted list, or one
// OMS instrument ID.
type SIPListItem struct {
	Exchange string `json:"exchange,omitempty"`
	Symbol   string `json:"symbol,omitempty"`
	ISIN     string `json:"isin,omitempty"`
	Name     string `json:"name,omitempty"`
	Note     string `json:"note,omitempty"` // category, restriction reason
	Token    string `json:"token,omitempty"`
}

// SIPList is an uploaded list.
type SIPList struct {
	Kind       string        `json:"kind"` // eligible, restricted, tokens
	Items      []SIPListItem `json:"items"`
	File       string        `json:"file,omitempty"`
	UploadedAt string        `json:"uploaded_at,omitempty"`
	UploadedBy string        `json:"uploaded_by,omitempty"`
}

// SIPListKinds are the lists the firm keeps.
var SIPListKinds = map[string]string{
	"eligible":   "Scrips allowed for SIPs (e.g. the top 250 by market value and ETFs): Symbol and/or ISIN, optional Exchange, Name, Category",
	"restricted": "Scrips never allowed (the exchanges' ASM and GSM lists, other restrictions): Symbol and/or ISIN, optional Reason",
	"tokens":     "OMS instrument IDs for API order entry (Symphony XTS exchangeInstrumentID): Exchange, Symbol, InstrumentID",
}

func (o *Ops) sipList(ctx context.Context, tenant, kind string) SIPList {
	l, _, _ := docs.GetOr(ctx, o.Docs, tenant, cSIPList, kind, SIPList{Kind: kind})
	if l.Items == nil {
		l.Items = []SIPListItem{}
	}
	return l
}

// StockSIPList returns one of the firm's lists.
func (o *Ops) StockSIPList(ctx context.Context, tenant, kind string) (SIPList, error) {
	if _, ok := SIPListKinds[kind]; !ok {
		return SIPList{}, ErrNotFound
	}
	return o.sipList(ctx, tenant, kind), nil
}

// UploadStockSIPList replaces a list from a CSV with a header row.
func (o *Ops) UploadStockSIPList(ctx context.Context, tenant, actor, kind, file string, data []byte) (SIPList, error) {
	if err := o.require(ctx, tenant, actor, "Uploading stock SIP scrip lists", RoleCompliance, RoleRisk); err != nil {
		return SIPList{}, err
	}
	if _, ok := SIPListKinds[kind]; !ok {
		return SIPList{}, invalid("the list is eligible, restricted or tokens")
	}
	if len(data) == 0 || len(data) > 5<<20 {
		return SIPList{}, invalid("upload a CSV file of up to 5 MB")
	}
	rd := csv.NewReader(bytes.NewReader(bytes.TrimPrefix(data, []byte("\xef\xbb\xbf"))))
	rd.FieldsPerRecord, rd.TrimLeadingSpace = -1, true
	head, err := rd.Read()
	if err != nil {
		return SIPList{}, invalid("the file has no header row")
	}
	col := map[string]int{}
	for i, h := range head {
		k := strings.ToLower(strings.NewReplacer(" ", "", "_", "", "-", "").Replace(strings.TrimSpace(h)))
		col[k] = i
	}
	pick := func(rec []string, names ...string) string {
		for _, n := range names {
			if i, ok := col[n]; ok && i < len(rec) {
				if v := strings.TrimSpace(rec[i]); v != "" {
					return v
				}
			}
		}
		return ""
	}
	l := SIPList{Kind: kind, Items: []SIPListItem{}, File: file, UploadedAt: o.now().Format(time.RFC3339), UploadedBy: actor}
	line := 1
	for {
		rec, err := rd.Read()
		if err == io.EOF {
			break
		}
		line++
		if err != nil {
			return SIPList{}, invalid("line %d: %v", line, err)
		}
		it := SIPListItem{Exchange: strings.ToUpper(pick(rec, "exchange", "exch")), Symbol: strings.ToUpper(pick(rec, "symbol", "tradingsymbol", "scrip")),
			ISIN: strings.ToUpper(pick(rec, "isin", "isincode")), Name: pick(rec, "name", "company", "companyname"),
			Note: pick(rec, "category", "reason", "stage", "note", "series"), Token: pick(rec, "instrumentid", "exchangeinstrumentid", "token")}
		if it.Symbol == "" && it.ISIN == "" {
			continue
		}
		if it.ISIN != "" && len(it.ISIN) != 12 {
			return SIPList{}, invalid("line %d: ISIN %q is not 12 characters", line, it.ISIN)
		}
		if kind == "tokens" {
			if it.Symbol == "" || it.Token == "" {
				return SIPList{}, invalid("line %d: the instrument list needs Exchange, Symbol and InstrumentID", line)
			}
			if _, err := strconv.ParseInt(it.Token, 10, 64); err != nil {
				return SIPList{}, invalid("line %d: instrument ID %q is not a number", line, it.Token)
			}
			it.Exchange = firstOf(it.Exchange, "NSE")
		}
		l.Items = append(l.Items, it)
		if len(l.Items) > 20000 {
			return SIPList{}, invalid("a list holds at most 20,000 scrips")
		}
	}
	if err := docs.Upsert(ctx, o.Docs, tenant, cSIPList, kind, l, actor); err != nil {
		return l, err
	}
	o.log(ctx, tenant, actor, "stocksip.list", kind, map[string]any{"items": len(l.Items), "file": file})
	return l, nil
}

func (l SIPList) find(exchange, symbol, isin string) (SIPListItem, bool) {
	for _, it := range l.Items {
		if it.Exchange != "" && exchange != "" && it.Exchange != exchange {
			continue
		}
		if (isin != "" && it.ISIN == isin) || (symbol != "" && it.Symbol == symbol) {
			return it, true
		}
	}
	return SIPListItem{}, false
}

// T2T and restricted series and groups, from the security masters: NSE
// series BE and BZ are trade-for-trade; BSE groups T, TS, XT and Z are
// trade-for-trade or restricted.
var (
	sipT2TSeries   = map[string]bool{"BE": true, "BZ": true}
	sipBSEBarGroup = map[string]bool{"T": true, "TS": true, "XT": true, "Z": true}
)

// sipScrip finds a scrip in the day's market and checks it may be bought
// through a SIP. The reason is "" when it may.
func (o *Ops) sipScrip(ctx context.Context, tenant string, cfg SIPSettings, look Lookup, exchange, symbol, isin string) (Instrument, string) {
	symbol, isin = strings.ToUpper(strings.TrimSpace(symbol)), strings.ToUpper(strings.TrimSpace(isin))
	var inst Instrument
	ok := false
	if isin != "" {
		inst, ok = look.ByISIN(isin)
	}
	if !ok && symbol != "" {
		inst, ok = look.Get(exchange, "CM", symbol+"|EQ||")
	}
	if !ok || inst.Segment != "CM" || (inst.Type != "" && inst.Type != "EQ") {
		return inst, fmt.Sprintf("%s is not in today's security list (not traded, suspended, or not an equity share or ETF)", firstOf(symbol, isin))
	}
	return inst, o.sipEligible(ctx, tenant, cfg, exchange, inst)
}

func (o *Ops) sipEligible(ctx context.Context, tenant string, cfg SIPSettings, exchange string, inst Instrument) string {
	name := inst.Symbol
	if it, bad := o.sipList(ctx, tenant, "restricted").find("", inst.Symbol, inst.ISIN); bad {
		return name + " is on the firm's restricted list" + map[bool]string{true: " (" + it.Note + ")", false: ""}[it.Note != ""] + ", so it cannot be bought through a SIP"
	}
	if inst.ISIN != "" {
		if ref, _, err := docs.Get[SecRef](ctx, o.Docs, tenant, cSecRef, inst.ISIN); err == nil {
			switch {
			case sipT2TSeries[strings.ToUpper(ref.Series)]:
				return name + " trades in the trade-for-trade segment (series " + ref.Series + "), which SIPs do not buy"
			case exchange == "BSE" && sipBSEBarGroup[strings.ToUpper(ref.BSEGrp)]:
				return name + " is in BSE group " + ref.BSEGrp + " (trade-for-trade or restricted), which SIPs do not buy"
			case strings.Contains(strings.ToUpper(ref.Status), "SUSP"):
				return name + " is suspended (" + ref.Status + ")"
			}
		}
	}
	switch cfg.Eligibility {
	case "list":
		if _, ok := o.sipList(ctx, tenant, "eligible").find("", inst.Symbol, inst.ISIN); !ok {
			return name + " is not on the firm's list of scrips for SIPs"
		}
	default:
		if inst.ISIN != "" && !strings.HasPrefix(inst.ISIN, "INE") && !strings.HasPrefix(inst.ISIN, "INF") {
			return name + " is not an equity share or ETF"
		}
	}
	return ""
}

// sipPrice is the instrument's last traded price, else its last close.
func sipPrice(i Instrument) money.Dec {
	if i.LTP.Sign() > 0 {
		return i.LTP
	}
	return i.Close
}
