var reHHMM = regexp.MustCompile(`^([01][0-9]|2[0-3]):[0-5][0-9]$`)

// SaveStockSIPSettings checks and stores the firm's SIP rules. The order
// type, placement time and algo tagging are a compliance decision.
func (o *Ops) SaveStockSIPSettings(ctx context.Context, tenant, actor string, s SIPSettings) (SIPSettings, error) {
	if err := o.require(ctx, tenant, actor, "Setting up stock SIPs", RoleCompliance); err != nil {
		return s, err
	}
	old := o.sipSettings(ctx, tenant)
	s.OrderType = strings.ToUpper(strings.TrimSpace(s.OrderType))
	if s.OrderType != "MARKET" && s.OrderType != "LIMIT" {
		return s, invalid("order type is MARKET (with market protection) or LIMIT")
	}
	p, err := money.ParseDec(firstOf(strings.TrimSpace(s.ProtectionPct), "0"))
	if err != nil || p.Sign() < 0 || p.Cmp(money.DecInt(20)) > 0 {
		return s, invalid("the protection (cushion above the last price) is a percentage from 0 to 20")
	}
	s.ProtectionPct = p.String()
	tick, err := money.ParseDec(firstOf(strings.TrimSpace(s.TickSize), "0.05"))
	if err != nil || tick.Sign() <= 0 || tick.Cmp(money.DecInt(100)) > 0 {
		return s, invalid("the tick size is a price step such as 0.05")
	}
	s.TickSize = tick.String()
	if !reHHMM.MatchString(s.PlaceAt) || s.PlaceAt < "09:15" || s.PlaceAt > "15:00" {
		return s, invalid("place SIP orders between 09:15 and 15:00 (HH:MM)")
	}
	switch s.Router {
	case "basket", "xts", "other":
	default:
		return s, invalid("orders go to the OMS by basket file, Symphony XTS or another OMS API")
	}
	if s.BasketFormat == "" {
		s.BasketFormat = "stocksip-basket"
	}
	if _, err := sipBasketSpec(s.BasketFormat); err != nil {
		return s, err
	}
	if s.Eligibility != "list" && s.Eligibility != "any" {
		return s, invalid("scrips allowed are the firm's list, or any equity share or ETF")
	}
	if s.MaxFailures < 1 || s.MaxFailures > 24 {
		return s, invalid("a SIP stops after 1 to 24 failed instalments in a row")
	}
	if s.MinAmount < 0 || s.BrokeragePerInstalment < 0 {
		return s, invalid("amounts cannot be negative")
	}
	s.BrokerageChannel = strings.ToLower(strings.TrimSpace(s.BrokerageChannel))
	if s.BrokerageChannel != "" && !charges.ValidChannel(s.BrokerageChannel) {
		return s, invalid("the brokerage channel is a channel name from Brokerage setup, e.g. sip")
	}
	s.AlgoID = strings.TrimSpace(s.AlgoID)
	if s.AlgoTag {
		if s.AlgoID == "" {
			return s, invalid("give the algo ID the exchange approved for SIP orders, or switch algo tagging off")
		}
		if s.OrderType == "MARKET" {
			return s, invalid("NSE does not accept market orders from algos: use limit orders when SIP orders are tagged as algo")
		}
	}
	if s.TopupCap <= 0 || s.TopupCap > sipTopupLimit {
		return s, invalid("a top-up is at most ₹15,000 (RBI's limit for e-mandate debits without additional authentication)")
	}
	if !reHHMM.MatchString(s.TopupAt) || s.TopupAt >= "21:00" {
		return s, invalid("give the time top-up debits are raised as HH:MM, before 21:00 (Cashfree takes next-day UPI AutoPay debits only before then)")
	}
	if s.Topups {
		if c, _, err := docs.Get[Connection](ctx, o.Docs, tenant, cConn, connSIPMandate); err != nil || c.Status == "Not set" {
			return s, invalid("set up the mandate provider in Settings → Connections (Stock SIP top-ups) before switching top-ups on")
		}
	}
	s.ConsentText = strings.TrimSpace(s.ConsentText)
	if s.ConsentText == "" {
		s.ConsentText = defaultSIPConsent
	}
	if len(s.ConsentText) > 4000 {
		return s, invalid("the consent wording is limited to 4,000 characters")
	}
	s.ConsentVersion = max(old.ConsentVersion, 1)
	if s.ConsentText != old.ConsentText {
		s.ConsentVersion++
	}
	now := o.now().Format(time.RFC3339)
	s.DecidedBy, s.DecidedAt = old.DecidedBy, old.DecidedAt
	if s.OrderType != old.OrderType || s.ProtectionPct != old.ProtectionPct || s.PlaceAt != old.PlaceAt || s.AlgoTag != old.AlgoTag || s.AlgoID != old.AlgoID || s.DecidedBy == "" {
		s.DecidedBy, s.DecidedAt = actor, now
	}
	s.UpdatedBy, s.UpdatedAt = actor, now
	if err := docs.Upsert(ctx, o.Docs, tenant, cSIPConf, "main", s, actor); err != nil {
		return s, err
	}
	o.log(ctx, tenant, actor, "stocksip.settings", "settings", map[string]any{"enabled": s.Enabled, "order_type": s.OrderType, "protection_pct": s.ProtectionPct,
		"place_at": s.PlaceAt, "router": s.Router, "algo_tag": s.AlgoTag, "eligibility": s.Eligibility, "topups": s.Topups, "consent_version": s.ConsentVersion})
	return s, nil
}

